export interface MapThemeSpec {
  skyColorHex: string;
  fogDensity: number;
  keyLightColorHex: string;
  keyLightIntensity: number;
  hemiSkyHex: string;
  hemiGroundHex: string;
  groundBaseHex: string;
  groundAccentHex: string;
  roadColorHex: string;
  roadBorderHex: string;
}

export interface RoadSegmentSpec {
  id: string;
  startX: number;
  startZ: number;
  endX: number;
  endZ: number;
  width: number;
}

export interface BuildingSpec {
  id: string;
  name: string;
  areaName: string;
  x: number;
  z: number;
  width: number;
  height: number;
  depth: number;
  rotationY: number;
  style: BuildingStyle;
  floors?: number;
  wallColorHex: string;
  roofColorHex: string;
  accentColorHex: string;
  placeholderModelKey: string;
}

export interface ObstacleSpec {
  id: string;
  x: number;
  z: number;
  width: number;
  height: number;
  depth: number;
  rotationY: number;
  colorHex: string;
  kind: 'crate' | 'barrier' | 'boulder' | 'container';
}

export interface MapAreaLabel {
  name: string;
  x: number;
  z: number;
  kind: 'village' | 'residential' | 'open' | 'loot';
}

export interface EnvironmentScatterSpec {
  rockCount: number;
  rockColorHex: string;
  pineTreeCount: number;
  broadleafTreeCount: number;
  snowTreeCount: number;
  mountainCount: number;
  cactusCount?: number;
  mesaCount?: number;
}

export interface MapConfig {
  id: MapId;
  name: string;
  subtitle: string;
  biome: BiomeType;
  isWaitingArena?: boolean;
  isTrainingGround?: boolean;
  radiusMeters: number;
  maxPlayers: number;
  terrainAmplitude: number;
  terrainFrequency: number;
  theme: MapThemeSpec;
  bounds: MapBoundsConfig;
  zoneConfig: ZoneConfiguration;
  roads: readonly RoadSegmentSpec[];
  areas: readonly MapAreaLabel[];
  buildings: readonly BuildingSpec[];
  obstacles: readonly ObstacleSpec[];
  spawnPoints: readonly SpawnPointSpec[];
  lootPoints: readonly LootPointSpec[];
  scatter: EnvironmentScatterSpec;
}

