const SKIN_BY_ID = new Map(WEAPON_SKIN_CATALOG.map((s) => [s.id, s]));

export function getWeaponSkinById(skinId?: string | null): WeaponSkinDefinition | undefined {
  if (!skinId) return undefined;
  return SKIN_BY_ID.get(skinId);
}

export function getWeaponSkinsForWeapon(weaponId: string): WeaponSkinDefinition[] {
  return WEAPON_SKIN_CATALOG.filter((s) => s.weaponId === weaponId);
}

export function isValidWeaponSkinId(skinId: unknown): skinId is string {
  return typeof skinId === 'string' && SKIN_BY_ID.has(skinId);
}
