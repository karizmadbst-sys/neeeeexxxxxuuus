export type WeaponInventoryGroup = 'LARGE' | 'PISTOL' | 'MELEE';
export type WeaponSlotIndex = 0 | 1 | 2 | 3;
export const WEAPON_SLOT_COUNT = 4;

export function getWeaponInventoryGroup(type: WeaponDefinition['type']): WeaponInventoryGroup {
  if (type === 'PISTOL') return 'PISTOL';
  if (type === 'MELEE') return 'MELEE';
  return 'LARGE';
}

export function getAllowedSlotsForWeaponGroup(
  group: WeaponInventoryGroup,
): readonly WeaponSlotIndex[] {
  if (group === 'PISTOL') return [2];
  if (group === 'MELEE') return [3];
  return [0, 1];
}

export function getWeaponSlotGroup(slotIndex: WeaponSlotIndex): WeaponInventoryGroup {
  if (slotIndex === 2) return 'PISTOL';
  if (slotIndex === 3) return 'MELEE';
  return 'LARGE';
}
